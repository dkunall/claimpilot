package com.claimpilot.policy.application;

import com.claimpilot.document.application.ObjectStore;
import com.claimpilot.document.application.PdfRenderer;
import com.claimpilot.payment.domain.Payment;
import com.claimpilot.policy.domain.Policy;
import com.claimpilot.policy.domain.PolicyVersion;
import com.claimpilot.shared.config.ClaimPilotProperties;
import com.claimpilot.shared.domain.Money;
import org.springframework.stereotype.Service;

import java.time.Duration;
import java.util.ArrayList;
import java.util.List;

/**
 * Policy schedules and payment receipts as PDFs. Schedules are written to the object store keyed by policy
 * version, so a schedule never changes under a link someone already has; the API hands out presigned GETs.
 */
@Service
public class PolicyDocuments {

    private final ObjectStore store;
    private final PdfRenderer pdf;
    private final Duration ttl;

    public PolicyDocuments(ObjectStore store, PdfRenderer pdf, ClaimPilotProperties props) {
        this.store = store;
        this.pdf = pdf;
        this.ttl = props.storage().presignTtl();
    }

    public static String scheduleKey(Policy p) {
        return "policies/" + p.id() + "/schedule-v" + p.lockVersion() + ".pdf";
    }

    public byte[] schedule(Policy p, List<PolicyVersion> current) {
        List<String[]> fields = new ArrayList<>();
        fields.add(new String[] {"Policy number", p.number()});
        fields.add(new String[] {"Policy holder", p.holderName()});
        fields.add(new String[] {"Product", p.productId() + " v" + p.productVersion()});
        fields.add(new String[] {"Status", p.status().name()});
        fields.add(new String[] {"Term", p.termStart() + " to " + p.termEnd()});
        List<List<String>> rows = new ArrayList<>();
        for (PolicyVersion v : current) {
            for (var c : v.coverage().coverages()) {
                rows.add(List.of(v.validFrom() + " to " + v.validTo(), c.name(), Money.inr(c.limitMinor()),
                        Money.inr(c.deductibleMinor()), Money.inr(v.annualPremiumMinor())));
            }
        }
        return pdf.render("Policy schedule", fields,
                List.of("Cover period", "Coverage", "Limit", "Deductible", "Annual premium (incl. tax)"), rows,
                "Synthetic document generated by ClaimPilot, a demo system. Not an insurance contract.");
    }

    public ObjectStore.Presigned scheduleLink(Policy p, List<PolicyVersion> current) {
        String key = scheduleKey(p);
        if (store.sizeOf(key).isEmpty()) {
            store.put(key, schedule(p, current), "application/pdf");
        }
        return store.presignGet(key, ttl);
    }

    public byte[] receipt(Policy p, Payment pay) {
        return pdf.render("Payment receipt " + pay.receiptNo(), List.of(
                new String[] {"Receipt", pay.receiptNo()},
                new String[] {"Policy", p.number()},
                new String[] {"Paid by", p.holderName()},
                new String[] {"Kind", pay.kind().name()},
                new String[] {"Amount", Money.inr(pay.amountMinor())},
                new String[] {"Gateway reference", pay.gatewayRef()},
                new String[] {"Date", pay.createdAt().toString()}),
                List.of(), List.of(), "Synthetic document generated by ClaimPilot, a demo system.");
    }
}
